// Generates src/tools.generated.ts from the live Caelara Labs catalog (100 endpoints in 10 suites).
//   node scripts/generate.mjs                                   reads https://caelaralabs.com/catalog.json and the api x402 manifest
//   node scripts/generate.mjs --catalog ./catalog.json --manifest ./x402-manifest.json
// Output is deterministic: running it twice on the same catalog produces identical bytes.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve, dirname } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const args = process.argv.slice(2)
const opt = (name, def) => (args.includes(name) ? args[args.indexOf(name) + 1] : def)
const catalogSrc = opt('--catalog', 'https://caelaralabs.com/catalog.json')
const manifestSrc = opt('--manifest', 'https://api.caelaralabs.com/x402-manifest.json')

async function load(src) {
  if (/^https?:\/\//.test(src)) {
    const r = await fetch(src, { signal: AbortSignal.timeout(30000) })
    if (!r.ok) throw new Error(`${src}: HTTP ${r.status}`)
    return r.json()
  }
  return JSON.parse(readFileSync(src, 'utf8'))
}

const catalog = await load(catalogSrc)
const manifest = await load(manifestSrc)
const first = manifest.resources[0]
const payTo = first.payTo
const asset = first.asset.address
if (!/^0x[0-9a-fA-F]{40}$/.test(payTo) || !/^0x[0-9a-fA-F]{40}$/.test(asset)) throw new Error('manifest payTo/asset is not an address')

const tools = []
for (const s of catalog.suites) {
  for (const e of s.endpoints) {
    const tool = e.path.replace('/v1/', '').replace(/-/g, '_')
    tools.push({
      name: `${s.id}_${tool}`,
      tool,
      suite: s.id,
      host: s.host,
      path: e.path,
      method: e.method,
      tier: e.tier,
      priceUsdc: e.price_usdc,
      summary: e.summary,
      params: e.params.map((p) => ({ name: p.name, in: p.in, type: p.type, required: !!p.required, description: p.description })),
    })
  }
}
if (new Set(tools.map((t) => t.name)).size !== tools.length) throw new Error('tool names are not unique')

const counts = { suites: catalog.suites.length, endpoints: tools.length, composites: tools.filter((t) => t.tier === 'composite').length, atomics: tools.filter((t) => t.tier === 'atomic').length }
const origin = /^https?:\/\//.test(catalogSrc) ? catalogSrc : 'catalog.json'
const out = `// GENERATED by scripts/generate.mjs from ${origin}. Do not edit by hand.
import type { ToolDef } from './types.js'

export const PAY_TO = ${JSON.stringify(payTo)}
export const USDC_BASE = ${JSON.stringify(asset)}
export const PRICES_USDC = ${JSON.stringify(catalog.prices_usdc)} as const
export const CATALOG_COUNTS = ${JSON.stringify(counts)} as const

export const TOOLS: readonly ToolDef[] = ${JSON.stringify(tools, null, 2)}
`
mkdirSync(resolve(here, '../src'), { recursive: true })
writeFileSync(resolve(here, '../src/tools.generated.ts'), out)
console.log(`wrote src/tools.generated.ts: ${counts.endpoints} tools in ${counts.suites} suites (${counts.composites} composite, ${counts.atomics} atomic), payTo ${payTo}`)
